/**
 * Canvas drawing helpers shared by both overlays.
 *
 * Font stacks and colours live in ./tokens — this file is geometry only.
 */

/**
 * Rounded rectangle path.
 *
 * Hand-rolled rather than using ctx.roundRect, which is still absent on older
 * Safari and throws rather than degrading. The radius is clamped so a large value
 * on a small box produces a pill instead of an inverted path.
 */
export function roundedRectPath(
  ctx: CanvasRenderingContext2D,
  x: number,
  y: number,
  w: number,
  h: number,
  r: number,
): void {
  const radius = Math.max(0, Math.min(r, w / 2, h / 2));
  ctx.beginPath();
  ctx.moveTo(x + radius, y);
  ctx.lineTo(x + w - radius, y);
  ctx.quadraticCurveTo(x + w, y, x + w, y + radius);
  ctx.lineTo(x + w, y + h - radius);
  ctx.quadraticCurveTo(x + w, y + h, x + w - radius, y + h);
  ctx.lineTo(x + radius, y + h);
  ctx.quadraticCurveTo(x, y + h, x, y + h - radius);
  ctx.lineTo(x, y + radius);
  ctx.quadraticCurveTo(x, y, x + radius, y);
  ctx.closePath();
}
